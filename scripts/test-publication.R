write_table <- function(name, data) write.csv(data, file.path("data", paste0(name, ".csv")), row.names = FALSE, na = "")
tryCatch({
  source("R/publication.R", local = .GlobalEnv)
  output <- function(fn) paste(capture.output(fn()), collapse = "\n")
  fails <- function(fn) stopifnot(tryCatch({fn(); FALSE}, error = function(e) TRUE))
  validate <- function() source("scripts/check.R", local = new.env())
  validate(); id <- read_data("measures")$id[1]
  stopifnot(is.null(result_record(id)), grepl("Certification pending.", output(function() measure_vote_share(id)), fixed = TRUE))
  stopifnot(html_escape('<script>"&') == '&lt;script&gt;&quot;&amp;')
  sources <- read_data("sources")
  fixture <- data.frame(source_id="test-certified", title="Synthetic <record>", publisher="Test", url="https://example.org/test", published_date="2020-01-01", accessed_date="2020-01-02", notes="fixture", stringsAsFactors=FALSE)
  write_table("sources", rbind(sources, fixture))
  counts <- data.frame(measure_id=id, for_votes="6000", against_votes="4000", certified_outcome="Passed", certified_date="2020-01-01", source_id="test-certified", stringsAsFactors=FALSE)
  write_table("results", counts); validate()
  result <- result_record(id); stopifnot(result$for_pct == 60, result$against_pct == 40, result$margin_pp == 20)
  html <- output(function() ballot_explanation(id)); stopifnot(grepl("60.0%", html, fixed=TRUE), grepl("6,000", html, fixed=TRUE), grepl("Synthetic &lt;record&gt;", html, fixed=TRUE))
  invalid <- counts; invalid$against_votes <- "-1"; write_table("results", invalid); fails(validate); write_table("results", counts)
  cycles <- read_data("elections"); extra <- cycles[1, ]; extra$cycle_id <- "2028-general"; extra$year <- "2028"; extra$election_date <- "2028-11-07"; extra$title <- "2028 General Election"; extra$path <- "elections/2028/general/index.qmd"; extra$published <- "false"
  dir.create("elections/2028/general", recursive=TRUE); file.copy("elections/2026/general/index.qmd", "elections/2028/general/index.qmd")
  write_table("elections", rbind(cycles, extra)); validate()
  stopifnot(nrow(published_elections()) == 1L, grepl("2026 General Election", output(election_index), fixed=TRUE), identical(output(latest_articles), ""))
  message("PASS: cycle-scoped records, pending and certified results, escaping, validation, and empty article handling.")
}, finally={setwd(original); unlink(sandbox, recursive=TRUE)})
