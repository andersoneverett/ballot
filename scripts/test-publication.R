# Integration checks in a disposable workspace; synthetic records never enter site data.
original <- getwd()
sandbox <- tempfile("ballot-tests-")
dir.create(sandbox)
for (folder in c("R", "scripts", "data", "measures")) file.copy(folder, sandbox, recursive = TRUE)
setwd(sandbox)
on.exit <- NULL
write_table <- function(name, data) write.csv(data, file.path("data", paste0(name, ".csv")), row.names = FALSE, na = "")
run_tests <- function() {
  source("R/publication.R", local = .GlobalEnv)
  output <- function(fn) paste(capture.output(fn()), collapse = "\n")
  fails <- function(fn) {
    failed <- tryCatch({fn(); FALSE}, error = function(e) TRUE)
    stopifnot(failed)
  }
  validate <- function() source("scripts/check.R", local = new.env())
  validate()
  id <- read_data("measures")$id[1]
  stopifnot(is.null(result_record(id)))
  stopifnot(grepl("Awaiting certified results", output(function() measure_vote_share(id)), fixed = TRUE))
  stopifnot(html_escape('<script>"&') == '&lt;script&gt;&quot;&amp;')
  sources <- read_data("sources")
  fixture <- data.frame(source_id = "test-certified", title = "Synthetic <record>", publisher = "Test fixture", url = "https://example.org/test", published_date = "2020-01-01", accessed_date = "2020-01-02", notes = "Synthetic test only", stringsAsFactors = FALSE)
  write_table("sources", rbind(sources, fixture))
  counts <- data.frame(measure_id = id, for_votes = "6000", against_votes = "4000", certified_outcome = "Passed", certified_date = "2020-01-01", source_id = "test-certified", stringsAsFactors = FALSE)
  write_table("results", counts)
  validate()
  result <- result_record(id)
  stopifnot(result$for_pct == 60, result$against_pct == 40, result$margin_pp == 20, result$total_votes == 10000)
  html <- output(function() measure_vote_share(id))
  stopifnot(grepl("60.0%", html, fixed = TRUE), grepl("6,000", html, fixed = TRUE), grepl("20.0 percentage points", html, fixed = TRUE), grepl("Synthetic &lt;record&gt;", html, fixed = TRUE))
  stopifnot(grepl("60.0% (6,000 votes)", output(tracker_table), fixed = TRUE))
  invalid <- counts; invalid$against_votes <- "-1"; write_table("results", invalid); fails(validate)
  invalid <- counts; invalid$for_votes <- ""; write_table("results", invalid); fails(validate)
  invalid <- counts; invalid$for_votes <- "0"; invalid$against_votes <- "0"; write_table("results", invalid); fails(validate)
  invalid <- counts; invalid$source_id <- "missing-source"; write_table("results", invalid); fails(validate)
  write_table("results", rbind(counts, counts)); fails(validate)
  write_table("results", counts)
  geography <- data.frame(geography_type = "precinct", geography_id = "001-001", jurisdiction = "Maryland", geography_name = "Synthetic precinct", boundary_vintage = "2020", boundary_source_id = "test-certified", stringsAsFactors = FALSE)
  write_table("geographies", geography)
  precinct <- data.frame(measure_id = id, geography_type = "precinct", geography_id = "001-001", geography_name = "Synthetic precinct", for_votes = "6001", against_votes = "4000", certified_date = "2020-01-01", source_id = "test-certified", stringsAsFactors = FALSE)
  write_table("precinct_results", precinct); fails(validate)
  precinct$for_votes <- "6000"; write_table("precinct_results", precinct); validate()
  stopifnot(grepl("60.0%", output(geography_table), fixed = TRUE))
  ledger <- read_data("spending")
  ledger[1, ] <- rep("", ncol(ledger))
  ledger[1, c("record_id", "measure_id", "project_id", "project_name", "stage", "amount_usd", "funding_source", "responsible_agency", "event_date", "location_name", "location_precision", "service_area", "source_id")] <- c("test-1", id, "test-project", "Synthetic <project>", "Budgeted", "1000.25", "Test funding", "Test agency", "2020-01-01", "Citywide", "citywide", "Whole city", "test-certified")
  write_table("spending", ledger); validate()
  stopifnot(grepl("Synthetic &lt;project&gt;", output(spending_table), fixed = TRUE), grepl("$1,000.25", output(spending_table), fixed = TRUE))
  ledger$latitude <- "39"; write_table("spending", ledger); fails(validate)
  message("PASS: empty states, vote counts and shares, margins, escaping, invalid results, geographic reconciliation, and spending validation.")
}
tryCatch(run_tests(), finally = {setwd(original); unlink(sandbox, recursive = TRUE)})
