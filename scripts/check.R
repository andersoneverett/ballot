source("R/publication.R")
source("R/measure-tags.R")
path_exists <- function(path) file.exists(sub("#.*$", "", path))
m <- read_data("measures"); s <- read_data("sources"); cycles <- read_data("elections"); r <- read_data("results")
stopifnot(nrow(m) > 0L, !anyDuplicated(m$id), !anyDuplicated(s$source_id), !anyDuplicated(cycles$cycle_id))
stopifnot(all(m$cycle_id %in% cycles$cycle_id), all(path_exists(cycles$path)), all(path_exists(m$guide_path)), all(path_exists(m$ballot_text_path)))
stopifnot(all(m$explanation_source_id %in% s$source_id), all(nzchar(m$explanation)), all(nzchar(m$if_for)), all(nzchar(m$if_against)))
stopifnot(!anyDuplicated(r$measure_id), all(r$measure_id %in% m$id), all(r$source_id %in% s$source_id))
if (nrow(r)) {
  stopifnot(all(r$outcome %in% c("Passed", "Failed")), all(r$status %in% c("Unofficial", "Certified")))
  supplied <- nzchar(r$for_votes)
  stopifnot(all(supplied == nzchar(r$against_votes)), all(grepl("^[0-9]+$", c(r$for_votes[supplied], r$against_votes[supplied]))))
}
validate_measure_tags(read_data("measure_tags"), m$id, s$source_id)
message("Data validated: ", nrow(m), " measures, ", nrow(r), " results.")
